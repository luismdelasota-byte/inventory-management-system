CREATE TABLE stock_movements (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code VARCHAR(20) NOT NULL UNIQUE,
    movement_type VARCHAR(10) NOT NULL,
    reason TEXT NOT NULL,
    user_id BIGINT NOT NULL,
    created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL,

    CONSTRAINT fk_stock_movements_user
        FOREIGN KEY (user_id)
        REFERENCES users(id)
);

CREATE TABLE stock_movement_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movement_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    quantity INTEGER NOT NULL,
    previous_stock INTEGER NOT NULL,
    new_stock INTEGER NOT NULL,

    CONSTRAINT fk_stock_items_movement
        FOREIGN KEY (movement_id)
        REFERENCES stock_movements(id),

    CONSTRAINT fk_stock_items_product
        FOREIGN KEY (product_id)
        REFERENCES products(id)
);

CREATE INDEX idx_stock_movements_user_id
    ON stock_movements(user_id);

CREATE INDEX idx_stock_items_movement_id
    ON stock_movement_items(movement_id);

CREATE INDEX idx_stock_items_product_id
    ON stock_movement_items(product_id);